import path from 'node:path';
import { fileURLToPath } from 'node:url';
import slugify from 'slugify';
import { loadDocs } from './docs';

const OUT_PATH = path.resolve(path.dirname(fileURLToPath(import.meta.url)), 'docComponents.generated.ts');

function toIdentifier(slug: string): string {
  const safe = slugify(slug, { replacement: '_', strict: true, lower: false });
  return `Doc_${/^\d/.test(safe) ? `_${safe}` : safe}`;
}

export async function generateDocsBarrel(): Promise<void> {
  const docs = await loadDocs();

  const lines: string[] = [];
  lines.push('// AUTO-GENERATED by generateDocsBarrel.ts — do not edit.');
  lines.push('');
  for (const doc of docs) {
    lines.push(`import ${toIdentifier(doc.slug)} from '../../../mochi/docs/${doc.filename}';`);
  }
  lines.push('');
  const firstDoc = docs[0];
  if (firstDoc) {
    lines.push(`export type DocComponent = typeof ${toIdentifier(firstDoc.slug)};`);
  } else {
    lines.push('export type DocComponent = unknown;');
  }
  lines.push('');
  lines.push('export const docComponents: Record<string, DocComponent> = {');
  for (const doc of docs) {
    lines.push(`  ${JSON.stringify(doc.slug)}: ${toIdentifier(doc.slug)},`);
  }
  lines.push('};');
  lines.push('');

  const content = lines.join('\n');

  const existing = await Bun.file(OUT_PATH)
    .text()
    .catch(() => null);
  if (existing === content) {
    return;
  }
  await Bun.write(OUT_PATH, content);
}

if (import.meta.main) {
  await generateDocsBarrel();
}
